import { randomBytes, timingSafeEqual } from 'node:crypto';
import type { IncomingHttpHeaders } from 'node:http';

import type { ApiOptions } from './client/api.ts';
import { camelKeys, toCamel } from './client/case.ts';
import { BotApi } from './telegram/api.ts';
import { TeleBunnyError } from './errors.ts';
import { Poller, type PollingOptions } from './updates/polling.ts';
import {
	UpdateType,
	type ParamsOf,
	type Update,
	type UpdatePayloads,
} from './telegram/index.ts';

export interface TeleBunnyOptions extends ApiOptions {
	/** Receives failed listeners and polling errors. Defaults to console.error. */
	onError?: (error: unknown) => void;
	/**
	 * Secret token sent with webhook requests and checked by `processUpdate`.
	 * 1-256 characters: A-Z, a-z, 0-9, `_` and `-`. When omitted, `setWebhook` generates one.
	 */
	webhookSecret?: string;
}

/** Request headers as given by node:http or the Fetch API. */
export type WebhookHeaders = IncomingHttpHeaders | Headers;

const SECRET_TOKEN_HEADER = 'x-telegram-bot-api-secret-token';

export type UpdateListener<K extends UpdateType> = (
	payload: UpdatePayloads[K],
	update: Update,
) => unknown;

type AnyListener = (payload: unknown, update: Update) => unknown;

interface ListenerEntry {
	listener: AnyListener;
	once: boolean;
}

const UPDATE_KEYS = Object.values(UpdateType).map(
	(type) => [type, toCamel(type)] as const,
);

class TeleBunny extends BotApi {
	readonly #token: string;
	readonly #onError: (error: unknown) => void;
	readonly #listeners = new Map<UpdateType, ListenerEntry[]>();
	#webhookSecret?: string;
	#poller?: Poller;

	constructor(token: string, options: TeleBunnyOptions = {}) {
		super(token, options);

		this.#token = token;
		this.#onError = options.onError ?? ((error) => console.error(error));
		this.#webhookSecret = options.webhookSecret;
	}

	get token(): string {
		return this.#token;
	}

	get isPolling(): boolean {
		return this.#poller?.running ?? false;
	}

	on<K extends UpdateType>(type: K, listener: UpdateListener<K>): this {
		return this.#addListener(type, listener as AnyListener, false);
	}

	once<K extends UpdateType>(type: K, listener: UpdateListener<K>): this {
		return this.#addListener(type, listener as AnyListener, true);
	}

	off<K extends UpdateType>(type: K, listener: UpdateListener<K>): this {
		const entries = this.#listeners.get(type);

		if (entries) {
			this.#listeners.set(
				type,
				entries.filter((entry) => entry.listener !== listener),
			);
		}

		return this;
	}

	#addListener(type: UpdateType, listener: AnyListener, once: boolean): this {
		const entries = this.#listeners.get(type) ?? [];

		entries.push({ listener, once });
		this.#listeners.set(type, entries);

		return this;
	}

	/** Starts long polling. Resolves once polling is running, rejects if the token is invalid. */
	async startPolling(options?: PollingOptions): Promise<void> {
		await this.stopPolling();

		const poller = new Poller(
			this.api,
			(update) => this.#dispatch(update),
			this.#onError,
			options,
		);

		this.#poller = poller;
		await poller.start();
	}

	/** Stops polling and waits for running listeners to finish. */
	async stopPolling(): Promise<void> {
		const poller = this.#poller;

		this.#poller = undefined;
		await poller?.stop();
	}

	/**
	 * Handles an update received by a webhook. Resolves after every listener has run;
	 * listener failures go to `onError`. Rejects if the secret token header does not
	 * match `webhookSecret` (or the one generated by `setWebhook`), or if the body
	 * is not an update.
	 *
	 * @param body raw request body or its parsed JSON
	 * @param headers request headers containing `X-Telegram-Bot-Api-Secret-Token`
	 */
	async processUpdate(
		body: object | Uint8Array | string,
		headers: WebhookHeaders,
	): Promise<void> {
		this.#verifySecret(headers);
		await this.#dispatch(parseUpdate(body));
	}

	#verifySecret(headers: WebhookHeaders): void {
		if (!this.#webhookSecret) {
			throw new TeleBunnyError(
				'Webhook secret is unknown: set webhookSecret or call setWebhook first',
			);
		}

		const received =
			headers instanceof Headers
				? headers.get(SECRET_TOKEN_HEADER)
				: headers[SECRET_TOKEN_HEADER];
		const expected = Buffer.from(this.#webhookSecret);
		const actual = Buffer.from(
			typeof received === 'string' ? received : '',
		);

		if (
			actual.length !== expected.length ||
			!timingSafeEqual(actual, expected)
		) {
			throw new TeleBunnyError('Invalid webhook secret token');
		}
	}

	async #dispatch(update: Update): Promise<void> {
		const [type, key] =
			UPDATE_KEYS.find(([, key]) => update[key] !== undefined) ?? [];

		if (!type || !key) return;

		const entries = this.#listeners.get(type);

		if (!entries) return;

		const payload = update[key];

		for (const entry of [...entries]) {
			if (entry.once) {
				this.#listeners.set(
					type,
					(this.#listeners.get(type) ?? []).filter(
						(item) => item !== entry,
					),
				);
			}

			try {
				await entry.listener(payload, update);
			} catch (error) {
				this.#onError(error);
			}
		}
	}

	/**
	 * Stops polling, then sets the webhook. `secretToken` defaults to `webhookSecret`,
	 * or a generated secret that `processUpdate` checks afterwards.
	 */
	override async setWebhook(
		url: string,
		options?: Omit<ParamsOf<'setWebhook'>, 'url'>,
	) {
		await this.stopPolling();

		const secretToken =
			options?.secretToken ??
			this.#webhookSecret ??
			randomBytes(32).toString('base64url');
		const result = await super.setWebhook(url, {
			...options,
			secretToken,
		});

		this.#webhookSecret = secretToken;

		return result;
	}
}

function parseUpdate(input: object | Uint8Array | string): Update {
	let value: unknown = input;

	if (typeof input === 'string' || input instanceof Uint8Array) {
		const text =
			typeof input === 'string' ? input : new TextDecoder().decode(input);

		try {
			value = JSON.parse(text);
		} catch (error) {
			throw new TeleBunnyError('Cannot parse incoming update', {
				cause: error,
			});
		}
	}

	const update = camelKeys<Partial<Update> | null>(value);

	if (typeof update?.updateId !== 'number') {
		throw new TeleBunnyError('Incoming data is not a Telegram update');
	}

	return update as Update;
}

export default TeleBunny;
export { TeleBunny };
